# Checklist generation
# ---------------------------------------------------------------------------

def generate_checklist(root: str, feature: str) -> str:
    """Return a Markdown quality checklist for ``feature``."""
    spec_ok = _artifact_status(root, feature, "spec.md").exists
    plan_ok = _artifact_status(root, feature, "plan.md").exists
    tasks_ok = _artifact_status(root, feature, "tasks.md").exists

    def _box(flag: bool) -> str:
        return "x" if flag else " "

    return _CHECKLIST_TEMPLATE.format(
        feature=feature,
        spec_check=_box(spec_ok),
        plan_check=_box(plan_ok),
        tasks_check=_box(tasks_ok),
    )
