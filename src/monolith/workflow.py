def _write_if_absent(path: str, content: str) -> Tuple[bool, str]:
    """Write ``content`` to ``path`` only if it does not already exist.

    Returns ``(was_created, path)``.
    """
    if os.path.exists(path):
        return False, path
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(content)
    return True, path


def scaffold_constitution(root: str) -> Tuple[bool, str]:
    return _write_if_absent(constitution_path(root), _CONSTITUTION_TEMPLATE)


def scaffold_spec(root: str, feature: str) -> Tuple[bool, str]:
    return _write_if_absent(
        artifact_path(root, feature, "spec.md"),
        _SPEC_TEMPLATE.format(feature=feature),
    )


def scaffold_plan(root: str, feature: str) -> Tuple[bool, str]:
    return _write_if_absent(
        artifact_path(root, feature, "plan.md"),
        _PLAN_TEMPLATE.format(feature=feature),
    )


def scaffold_data_model(root: str, feature: str) -> Tuple[bool, str]:
    return _write_if_absent(
        artifact_path(root, feature, "data-model.md"),
        _DATA_MODEL_TEMPLATE.format(feature=feature),
    )


def scaffold_contracts(root: str, feature: str) -> Tuple[bool, str]:
    path = os.path.join(feature_dir(root, feature), CONTRACTS_DIR, "README.md")
    return _write_if_absent(path, _CONTRACTS_README_TEMPLATE.format(feature=feature))


# ---------------------------------------------------------------------------
# Analyze — structural consistency check (offline, no LLM)
# ---------------------------------------------------------------------------

_PLACEHOLDER_RE = re.compile(
    r"<!--.*?-->|\bTODO\b|\bTBD\b",
    re.MULTILINE | re.DOTALL,
)
_HEADING_RE = re.compile(r"^#{1,6}\s+\S", re.MULTILINE)
_CHECKBOX_RE = re.compile(r"- \[[ x]\]")


@dataclass
class ArtifactStatus:
    name: str
    exists: bool
    word_count: int = 0
    heading_count: int = 0
    checkbox_count: int = 0
    unfilled: bool = False


def _read_file(path: str) -> Optional[str]:
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def _artifact_status(root: str, feature: str, name: str) -> ArtifactStatus:
    path = artifact_path(root, feature, name)
    text = _read_file(path)
    if text is None:
        return ArtifactStatus(name=name, exists=False)
    stripped = _PLACEHOLDER_RE.sub("", text)
    words = len(stripped.split())
    headings = len(_HEADING_RE.findall(text))
    checkboxes = len(_CHECKBOX_RE.findall(text))
    # Unfilled = still has generator comment AND very few real words.
    unfilled = "Generated by" in text and words < 60
    return ArtifactStatus(
        name=name,
        exists=True,
        word_count=words,
        heading_count=headings,
        checkbox_count=checkboxes,
        unfilled=unfilled,
    )


def analyze_feature(root: str, feature: str) -> List[str]:
    """Return plain-English findings for a feature's artifact set.

    Each finding is prefixed with ``OK``, ``WARN``, ``ERROR``, or ``INFO``.
    """
    findings: List[str] = []

    # Constitution
    if os.path.exists(constitution_path(root)):
        findings.append("OK    constitution.md exists")
    else:
        findings.append("WARN  constitution.md missing — run `monolith constitution`")

    # Required pipeline artifacts
    for name in PIPELINE_ARTIFACTS:
        s = _artifact_status(root, feature, name)
        if not s.exists:
            if name == "spec.md":
                hint = f"run `monolith specify {feature}`"
            elif name == "plan.md":
                hint = f"run `monolith plan <prd>` (or fill specs/{feature}/plan.md)"
            else:
                hint = "run `monolith tasks` after plan"
            findings.append(f"ERROR  {name} missing — {hint}")
        elif s.unfilled:
            findings.append(f"WARN  {name} has unfilled template placeholders")
        elif s.word_count < 30:
            findings.append(f"WARN  {name} is very thin ({s.word_count} words)")
        else:
            cb = f", {s.checkbox_count} checkboxes" if s.checkbox_count else ""
            findings.append(
                f"OK    {name}  ({s.word_count} words, {s.heading_count} sections{cb})"
            )

    # Optional artifacts
    dm = _artifact_status(root, feature, "data-model.md")
    if dm.exists and not dm.unfilled:
        findings.append(f"OK    data-model.md  ({dm.word_count} words)")
    elif dm.exists:
        findings.append("WARN  data-model.md has unfilled template placeholders")
    else:
        findings.append(
            f"INFO  data-model.md absent — add with `monolith specify --data-model {feature}`"
        )

    contracts_dir = os.path.join(feature_dir(root, feature), CONTRACTS_DIR)
    if os.path.isdir(contracts_dir):
        contracts = [f for f in os.listdir(contracts_dir) if f != "README.md"]
        n = len(contracts)
        findings.append(f"OK    contracts/  ({n} contract file{'s' if n != 1 else ''})")
    else:
        findings.append(
            f"INFO  contracts/ absent — add with `monolith specify --contracts {feature}`"
        )

    return findings


