"""Spec-Driven Development workflow — structured per-feature artifact management.

Monolith's SDD pipeline mirrors spec-kit's methodology adapted for Monolith's
offline, dependency-free philosophy:

    constitution → specify → clarify → plan → analyze → tasks → implement

Each feature lives under ``specs/<feature>/`` with standard artifact files:
    spec.md        functional requirements and user stories
    plan.md        technical architecture and stack decisions
    tasks.md       actionable task breakdown with dependencies
    data-model.md  entity and data model (optional)
    contracts/     API contracts, one file per endpoint (optional)

All scaffolding is template-based and deterministic — no LLM calls, no network.

Cross-artifact analysis and checklist generation live in
:mod:`monolith.analysis`; this module owns only path conventions, templates,
and scaffolding.
"""

from __future__ import annotations

import os
from typing import List, Tuple

# ---------------------------------------------------------------------------
# Directory / path conventions
# ---------------------------------------------------------------------------

SPECS_DIR = "specs"
CONSTITUTION_PATH = os.path.join(".monolith", "memory", "constitution.md")
CONTRACTS_DIR = "contracts"

#: Artifact names that form the required pipeline.
PIPELINE_ARTIFACTS = ("spec.md", "plan.md", "tasks.md")
#: Optional artifacts that improve coverage but are not blocking.
OPTIONAL_ARTIFACTS = ("data-model.md",)
ALL_ARTIFACTS = PIPELINE_ARTIFACTS + OPTIONAL_ARTIFACTS


def feature_dir(root: str, feature: str) -> str:
    return os.path.join(root, SPECS_DIR, feature)


def artifact_path(root: str, feature: str, artifact: str) -> str:
    return os.path.join(feature_dir(root, feature), artifact)


def constitution_path(root: str) -> str:
    return os.path.join(root, CONSTITUTION_PATH)


def list_features(root: str) -> List[str]:
    """Return sorted feature names found under ``specs/``."""
    specs_root = os.path.join(root, SPECS_DIR)
    if not os.path.isdir(specs_root):
        return []
    return sorted(
        name for name in os.listdir(specs_root)
        if os.path.isdir(os.path.join(specs_root, name))
    )


