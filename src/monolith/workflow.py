# ---------------------------------------------------------------------------
# Scaffold helpers
# ---------------------------------------------------------------------------

def _write_if_absent(path: str, content: str) -> Tuple[bool, str]:
    """Write ``content`` to ``path`` only if it does not already exist.

    Returns ``(was_created, path)``.
    """
    if os.path.exists(path):
        return False, path
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(content)
    return True, path


def scaffold_constitution(root: str) -> Tuple[bool, str]:
    return _write_if_absent(constitution_path(root), _CONSTITUTION_TEMPLATE)


def scaffold_spec(root: str, feature: str) -> Tuple[bool, str]:
    return _write_if_absent(
        artifact_path(root, feature, "spec.md"),
        _SPEC_TEMPLATE.format(feature=feature),
    )


def scaffold_plan(root: str, feature: str) -> Tuple[bool, str]:
    return _write_if_absent(
        artifact_path(root, feature, "plan.md"),
        _PLAN_TEMPLATE.format(feature=feature),
    )


def scaffold_data_model(root: str, feature: str) -> Tuple[bool, str]:
    return _write_if_absent(
        artifact_path(root, feature, "data-model.md"),
        _DATA_MODEL_TEMPLATE.format(feature=feature),
    )


def scaffold_contracts(root: str, feature: str) -> Tuple[bool, str]:
    path = os.path.join(feature_dir(root, feature), CONTRACTS_DIR, "README.md")
    return _write_if_absent(path, _CONTRACTS_README_TEMPLATE.format(feature=feature))
