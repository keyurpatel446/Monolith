_CHECKLIST_TEMPLATE = """\
# Quality Checklist: {feature}

## Spec and Planning
- [{spec_check}] `spec.md` written and reviewed
- [{plan_check}] `plan.md` matches spec requirements
- [{tasks_check}] `tasks.md` covers all spec sections
- [ ] All open questions resolved (no `?` placeholders in spec)
- [ ] Non-goals explicitly listed

## Implementation
- [ ] All acceptance criteria from spec satisfied
- [ ] Edge cases from `plan.md` handled in code
- [ ] No TODO / FIXME / HACK left in committed files

## Quality Gates
- [ ] Tests pass (`monolith run -- pytest` or equivalent)
- [ ] Lint/type-check passes (`monolith run -- ruff check .`)
- [ ] `monolith doctor` reports no issues
- [ ] `monolith analyze {feature}` reports no ERRORs

## Review
- [ ] PR description references this feature's spec
- [ ] Reviewer confirmed implementation matches spec
- [ ] CHANGELOG updated

_Generated by Monolith for `{feature}`. Edit as needed._
"""


def generate_checklist(root: str, feature: str) -> str:
    """Return a Markdown quality checklist for ``feature``."""

    def _box(name: str) -> str:
        return "x" if _artifact_status(root, feature, name).exists else " "

    return _CHECKLIST_TEMPLATE.format(
        feature=feature,
        spec_check=_box("spec.md"),
        plan_check=_box("plan.md"),
        tasks_check=_box("tasks.md"),
    )
